"""Show which wrong inputs the historical builder accepts. Run from the repository root."""

from __future__ import annotations

import csv
import json
import sqlite3
import subprocess
import sys
import tempfile
from contextlib import closing
from pathlib import Path

# Invented forward-strand site and versioned transcript. Position 2 in this
# four-base toy reference is G. There is no personal sample or human locus.
REFERENCE = "TGCA"
EXPECTED = ("rsSynthetic", "1", 2, REFERENCE[1], "A", "TOY.1", "+", "c.2G>A")
FIELDS = ("rsid", "chrom", "pos", "ref", "alt", "transcript_id", "strand", "hgvs_coding")
CASES = {
    "reference_first": ("G", "A", "c.2G>A"),
    "alphabetically_reversed": ("A", "G", "c.2A>G"),
    "coding_only_reversed": ("G", "A", "c.2A>G"),
}


def probe(folder: Path, mode: str, case: str) -> dict:
    ref, alt, coding = CASES[case]
    observed_input = ("rsSynthetic", "1", 2, ref, alt, "TOY.1", "+", coding)
    source = folder / (case + (".csv" if mode == "--seed-csv" else ".vcf"))
    if mode == "--seed-csv":
        with source.open("w", newline="") as handle:
            writer = csv.writer(handle)
            writer.writerow((*FIELDS, "mane_select"))
            writer.writerow((*observed_input, 0))
    else:
        source.write_text(
            "##fileformat=VCFv4.2\n"
            '##INFO=<ID=CSQ,Number=.,Type=String,Description="'
            'Format: Allele|Feature|STRAND|HGVSc">\n'
            "#CHROM\tPOS\tID\tREF\tALT\tQUAL\tFILTER\tINFO\n"
            f"1\t2\trsSynthetic\t{ref}\t{alt}\t.\t.\tCSQ={alt}|TOY.1|1|TOY.1:{coding}\n"
        )
    dest = folder / (source.name + ".db")
    subprocess.run(
        [sys.executable, "scripts/build_vep_bundle.py", mode, str(source), "--output", str(dest)],
        check=True,
        stdout=subprocess.DEVNULL,
    )
    with closing(sqlite3.connect(dest.as_uri() + "?mode=ro", uri=True)) as conn:
        rows = conn.execute("SELECT " + ", ".join(FIELDS) + " FROM vep_annotations").fetchall()
    if rows != [observed_input]:
        raise ValueError(f"{mode} failed to preserve the exact supplied {case} tuple")
    return {
        "mode": mode,
        "case": case,
        "stored_rows": len(rows),
        "matches_oracle": rows == [EXPECTED],
    }


def probe_genotype_input(folder: Path) -> list[dict]:
    """Feed three invented calls to the historical vendor-input CLI."""
    header = (
        "# This data file generated by 23andMe\n# GRCh37\n# rsid\tchromosome\tposition\tgenotype\n"
    )
    results = []
    for call in ("GA", "AG", "GG"):
        source = folder / f"synthetic-{call}.txt"
        source.write_text(header + f"rsSynthetic\t1\t2\t{call}\n")
        dest = folder / f"synthetic-{call}.vcf"
        subprocess.run(
            [sys.executable, "scripts/generate_vep_input.py", str(source), "-o", str(dest)],
            check=True,
            stdout=subprocess.DEVNULL,
        )
        records = [
            line.split("\t") for line in dest.read_text().splitlines() if not line.startswith("#")
        ]
        if (
            len(records) != 1
            or len(records[0]) != 8
            or records[0][:3] != ["1", "2", "rsSynthetic"]
        ):
            raise ValueError(
                "Historical vendor input must produce exactly the expected synthetic site"
            )
        results.append({"synthetic_input": call, "ref": records[0][3], "alt": records[0][4]})
    return results


def main() -> None:
    with tempfile.TemporaryDirectory() as directory:
        generator_results = probe_genotype_input(Path(directory))
        results = [
            probe(Path(directory), mode, case)
            for mode in ("--vep-vcf", "--seed-csv")
            for case in CASES
        ]
    for result in results:
        if result["stored_rows"] != 1 or result["matches_oracle"] != (
            result["case"] == "reference_first"
        ):
            raise SystemExit(f"Historical reproduction changed: {result}")
    if [(r["ref"], r["alt"]) for r in generator_results] != [("A", "G"), ("A", "G"), ("G", ".")]:
        raise SystemExit(f"Historical genotype-input behavior changed: {generator_results}")
    print(json.dumps({"genotype_input": generator_results, "sqlite_builder": results}, indent=2))


if __name__ == "__main__":
    main()
