SYNTHETIC_23ANDME = (
    b"# This data file generated by 23andMe\n"
    b"# reference human assembly build 37\n"
    b"# rsid\tchromosome\tposition\tgenotype\n"
    b"rs1\t1\t12345\tAA\n"
    b"rs2\t1\t12400\tAG\n"
)


@pytest.fixture
def registry(tmp_data_dir: Path, monkeypatch: pytest.MonkeyPatch):
    settings = Settings(data_dir=tmp_data_dir, wal_mode=False)
    engine = sa.create_engine(f"sqlite:///{settings.reference_db_path}")
    reference_metadata.create_all(engine)
    engine.dispose()

    reset_registry()
    reg = DBRegistry(settings)
    monkeypatch.setattr(ingest_route, "get_registry", lambda: reg)
    yield reg
    reg.dispose_all()
    reset_registry()


def _ingest(registry: DBRegistry) -> dict:
    return ingest_route._ingest_file(SYNTHETIC_23ANDME, "synthetic.txt")


def _hook_mid_build(registry: DBRegistry, monkeypatch: pytest.MonkeyPatch, action) -> dict:
    """Run ``action(sample_id)`` once the row is published but before the DB is built."""
    seen: dict = {}
    real = ingest_route.create_sample_tables

    def create_sample_tables_then_act(engine, *args, **kwargs):
        with registry.reference_engine.connect() as conn:
            sample_id = conn.execute(sa.select(sa.func.max(samples.c.id))).scalar_one()
        seen["sample_id"] = sample_id
        try:
            seen["result"] = action(sample_id)
        except SampleOperationConflictError as exc:
            seen["conflict"] = str(exc)
        return real(engine, *args, **kwargs)

    monkeypatch.setattr(ingest_route, "create_sample_tables", create_sample_tables_then_act)
    return seen


def _count(engine: sa.Engine, table: sa.Table) -> int:
    with engine.connect() as conn:
        return conn.execute(sa.select(sa.func.count()).select_from(table)).scalar_one()


class TestDeleteDuringIngest:
    def test_delete_mid_ingest_is_refused_and_leaves_no_stray_database(
        self, registry: DBRegistry, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """The #2573 window: the row is visible, the database is not built yet."""
        seen = _hook_mid_build(
            registry,
            monkeypatch,
            lambda sample_id: delete_sample_with_cascade(registry, sample_id),
        )

        response = _ingest(registry)

        assert "conflict" in seen, f"delete succeeded mid-ingest: {seen.get('result')!r}"
        assert "still being imported" in seen["conflict"]
        assert response["sample_id"] == seen["sample_id"]
        sample_db = registry.settings.data_dir / "samples" / f"sample_{seen['sample_id']}.db"
        assert sample_db.exists()
        with registry.reference_engine.connect() as conn:
            row = conn.execute(
                sa.select(samples.c.id).where(samples.c.id == seen["sample_id"])
            ).fetchone()
            job = conn.execute(sa.select(jobs).where(jobs.c.job_id == response["job_id"])).one()
        assert row is not None
        assert (job.job_type, job.status) == (SAMPLE_INGEST_JOB_TYPE, "complete")

    def test_delete_is_allowed_once_ingest_completes(self, registry: DBRegistry) -> None:
        response = _ingest(registry)

        result = delete_sample_with_cascade(registry, response["sample_id"])

        assert result is not None
        sample_db = registry.settings.data_dir / "samples" / f"sample_{response['sample_id']}.db"
        assert not sample_db.exists()
        assert _count(registry.reference_engine, samples) == 0

    def test_upload_refuses_an_id_an_active_delete_already_reserved(
        self, registry: DBRegistry
    ) -> None:
        """SQLite reuses a vacant rowid: the next upload would receive id 1."""
        now = datetime.now(UTC)
        with registry.reference_engine.begin() as conn:
            conn.execute(
                jobs.insert().values(
                    job_id="synthetic-delete:1",
                    sample_id=1,
                    job_type=SAMPLE_DELETE_JOB_TYPE,
                    status="running",
                    created_at=now,
                    updated_at=now,
                )
            )

        with pytest.raises(SampleOperationConflictError, match="still being deleted"):
            _ingest(registry)

        assert _count(registry.reference_engine, samples) == 0
        with registry.reference_engine.connect() as conn:
            ingest_rows = conn.execute(
                sa.select(sa.func.count())
                .select_from(jobs)
                .where(jobs.c.job_type == SAMPLE_INGEST_JOB_TYPE)
            ).scalar_one()
        assert ingest_rows == 0
        assert not (registry.settings.data_dir / "samples" / "sample_1.db").exists()


