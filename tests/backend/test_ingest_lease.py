"""Ingest runs off the event loop and holds a lease until its database is complete (#2574).

An upload publishes its ``samples`` row before it builds the database that row
names. While ingest ran on the event loop nothing else could reach the sample
meanwhile; it now runs in the threadpool, so these tests pin the guarantee the
loop used to provide by accident (#2573): no delete, annotation, export, merge
or LAI run can act on a sample that is still being imported, and a delete can
never leave this upload recreating ``sample_<id>.db`` at an id the registry no
longer holds.

All genotype rows here are synthetic.
"""

from __future__ import annotations

